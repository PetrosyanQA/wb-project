# ── оформление ──────────────────────────────────────────────────────────────
def set_font(run, size=None, bold=None, color=None, italic=None):
    run.font.name = FONT
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts"); rpr.append(rf)
    for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        rf.set(qn(a), FONT)
    if size: run.font.size = Pt(size)
    if bold is not None: run.bold = bold
    if italic is not None: run.italic = italic
    if color: run.font.color.rgb = RGBColor.from_string(color)


def shade(cell, hex_color):
    tcpr = cell._element.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), hex_color)
    tcpr.append(shd)


class Doc:
    def __init__(self):
        self.d = Document()
        st = self.d.styles["Normal"]
        st.font.name = FONT; st.font.size = Pt(10)
        st.element.rPr.rFonts.set(qn("w:cs"), FONT)
        for sec in self.d.sections:
            sec.left_margin = sec.right_margin = Cm(2); sec.top_margin = sec.bottom_margin = Cm(1.8)
        self.n = 0

    def h(self, text, level=1):
        if level == 1:
            self.n += 1
            text = f"{self.n}. {text}"
        p = self.d.add_heading("", level=level)
        set_font(p.add_run(text), size={0: 20, 1: 15, 2: 12, 3: 11}[level], bold=True, color="1F3864")
        return p

    def p(self, *parts, size=10, align=None, space=4):
        """parts: str или (str, 'b'|'i'|'bi')."""
        para = self.d.add_paragraph()
        para.paragraph_format.space_after = Pt(space)
        if align: para.alignment = align
        for x in parts:
            t, f = (x, "") if isinstance(x, str) else x
            set_font(para.add_run(t), size=size, bold="b" in f, italic="i" in f)
        return para

    def bullets(self, items, style="List Bullet"):
        for it in items:
            para = self.d.add_paragraph(style=style)
            para.paragraph_format.space_after = Pt(2)
            parts = it if isinstance(it, (list, tuple)) else [it]
            for x in parts:
                t, f = (x, "") if isinstance(x, str) else x
                set_font(para.add_run(t), size=10, bold="b" in f, italic="i" in f)

    def note(self, text):
        para = self.d.add_paragraph()
        para.paragraph_format.space_after = Pt(8)
        set_font(para.add_run(text), size=8, italic=True, color="595959")

    def table(self, header, rows, note=None, widths=None, highlight=None):
        t = self.d.add_table(rows=1, cols=len(header))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for i, h in enumerate(header):
            c = t.rows[0].cells[i]; c.text = ""
            set_font(c.paragraphs[0].add_run(str(h)), size=9, bold=True, color="FFFFFF")
            shade(c, "1F3864")
        for ri, r in enumerate(rows):
            cells = t.add_row().cells
            for i, v in enumerate(r):
                cells[i].text = ""
                bold = isinstance(v, tuple)
                txt = v[0] if bold else v
                set_font(cells[i].paragraphs[0].add_run("—" if txt is None else str(txt)), size=9, bold=bold)
                if highlight is not None and ri in highlight:
                    shade(cells[i], "E2EFDA")
        if widths:
            for row in t.rows:
                for i, w in enumerate(widths):
                    row.cells[i].width = Cm(w)
        if note:
            self.note(note)
        else:
            self.d.add_paragraph().paragraph_format.space_after = Pt(4)
        return t

    def box(self, text, fill="FFF2CC"):
        t = self.d.add_table(rows=1, cols=1); t.style = "Table Grid"
        c = t.rows[0].cells[0]; c.text = ""
        shade(c, fill)
        first = True
        for line in text.split("\n"):
            para = c.paragraphs[0] if first else c.add_paragraph()
            first = False
            set_font(para.add_run(line), size=9)
        self.d.add_paragraph().paragraph_format.space_after = Pt(2)

    def pagebreak(self):
        self.d.add_page_break()


def niche_dirs():
    """Уникальные ниши, по которым есть сохранённые выгрузки (папки data/raw/saleflow/<date>/<slug>)."""
    slugs = set()
    for path in glob.glob(os.path.join(ROOT, "2026-10-0*", "*")):
        name = os.path.basename(path)
        if os.path.isdir(path) and not name.startswith("subjects_"):
            slugs.add(name.split("-feb")[0].split("-jan")[0].split("-fmt")[0])
    return slugs


