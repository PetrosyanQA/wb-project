def ofasert_stems() -> list[str]:
    stems = []
    for line in (ROOT_DIR / "docs" / "ofasert_otkaz_list_2026-03-13.txt").read_text(encoding="utf-8").splitlines():
        line = line.strip(" -\t")
        if not line or line.startswith("#") or line.isupper():
            continue
        for item in re.split(r"[,;()/]", line):
            w = re.findall(r"[а-яё]{4,}", item.lower())
            if w:
                stems.append(w[0][:6])
    return sorted(set(stems))


def classify(r: dict, reg: dict, stems: list[str]) -> dict:
    name = r["name"]
    root, leaf = (name.split(" / ", 1) + [""])[:2]
    low, leaf_l = name.lower(), leaf.lower()
    chz, docs, flags = ROOT.get(root, DEFAULT)
    flags = set(flags)
    why = []
    if root in ("Красота", "Здоровье") and NON_COSMETIC.search(leaf_l):
        chz, docs = DEFAULT[:2]
    if any(re.search(r"\b" + re.escape(k), low) for k in reg["hard_exclude_keywords"]):
        flags.add("запрет"); why.append("жёсткий запрет (filters.yaml)")
    if chz != "да" and any(leaf_l.startswith(k) for k in reg["marking_keywords"]):    # сам товар, а не «аксессуары для …»
        chz = "да"; why.append("ЧЗ по ключевому слову (ПП 1954 и др.)")
    cert_hit = any(re.search(r"\b" + re.escape(k), leaf_l) for k in reg["certification_keywords"])
    special = next(((d, v) for rx, d, v in SPECIAL if rx.search(leaf_l)), None)
    if special and chz != "да":
        docs = special[0]
        if special[1].startswith("❌"):
            flags.add("запрет")
    if ELECTRO_LEAF.search(leaf):
        flags.add("батарея/электро")
    if BATTERY.search(leaf) and root not in ("Одежда", "Обувь"):
        flags.add("батарея/электро")
    if MAGNET.search(leaf):
        flags.add("магнит")
    if LIQUID.search(leaf):
        flags.add("жидкость")
    if BULKY.search(leaf):
        flags.add("габарит")
    if docs.startswith("обычно отказное"):
        if any(leaf_l.startswith(s) or (" " + s) in (" " + leaf_l) for s in stems):
            docs = "отказное письмо (есть в списке Ofa_Sert)"
        elif cert_hit:
            docs = "вероятно декларация (ключевое слово сертификации)"; why.append("ключевое слово сертификации")
    # [правило пользователя 2026-11-01] запрет ОДИН — магниты; ЧЗ / электроника / батареи — можно, с пометкой «что оформить»
    if "запрет" in flags:
        verdict = "❌ запрет"
    elif "магнит" in flags:
        verdict = "❌ магнит"
    elif chz == "да":
        verdict = "🟡 Честный знак — оформить маркировку"
    elif chz == "возможно":
        verdict = "❓ возможно ЧЗ / СГР — проверить"
    elif flags & {"электроника", "батарея/электро", "батарея"}:
        verdict = "🟡 электроника / батарея — документы (декларация, ЧЗ по ПП 1954?)"
    elif special:
        verdict = special[1]
    elif any(k in docs for k in ("декларац", "сертификат", "РУ ", "СГР")) and not docs.startswith(("обычно отказное", "отказное")):
        verdict = "🟡 нужна декларация / сертификат"
    elif "жидкость" in flags:
        verdict = "🟡 нужна декларация / СГР (жидкость, химия)"
    else:
        verdict = "🟢 без обязательных документов"
    if "габарит" in flags and verdict.startswith(("🟢", "🟡")):
        verdict += " (крупный)"
    rev = (r.get("revenue_estimated") or r.get("revenue") or 0) * (r.get("purchase_after_return") or 0) / 100
    return {"id": r["id"], "subject": leaf or root, "root": root, "rev_mln": round(rev / 1e6, 2),
            "median_price": r.get("median_price_final_with_sells"), "sellers": r.get("sellers_with_sells"),
            "chz": chz, "docs": docs, "flags": ", ".join(sorted(flags)) or "—", "verdict": verdict, "why": "; ".join(why)}


def main() -> None:
    reg = yaml.safe_load((ROOT_DIR / "config" / "filters.yaml").read_text(encoding="utf-8"))["regulatory"]
    stems = ofasert_stems()
    rows = {}
    # метрики — снимок 2026-07-31 (последний полный у Saleflow); предметы, которых там нет, — из «latest» (неполный, флаг в названии)
    for pat in ("latest", "jul2026", "jul2026_rev15m"):
        for f in glob.glob(str(ROOT_DIR / f"data/raw/saleflow/2026-10-11/all/{pat}/page_*.json")):
            for r in json.load(open(f, encoding="utf-8"))["data"]:
                rows[r["id"]] = r
    out = sorted((classify(r, reg, stems) for r in rows.values()), key=lambda x: -x["rev_mln"])
    json.dump(out, open(ROOT_DIR / "data" / "processed" / f"niche_requirements_{TODAY}.json", "w", encoding="utf-8"), ensure_ascii=False)

    from openpyxl import Workbook
    from openpyxl.styles import Font
    wb = Workbook()
    ws = wb.active
    ws.title = "Все предметы"
    ws.append(["ID", "Предмет", "Категория", "Выручка, млн ₽/мес", "Медиана цены, ₽", "Продавцов с продажами", "Честный знак",
               "Документы", "Ограничения", "Итог для нас", "Почему"])
    for x in out:
        ws.append([x[k] for k in ("id", "subject", "root", "rev_mln", "median_price", "sellers", "chz", "docs", "flags", "verdict", "why")])
    for c in ws[1]:
        c.font = Font(bold=True)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions
    for col, w in zip("ABCDEFGHIJK", (9, 34, 26, 12, 12, 12, 10, 48, 26, 34, 30)):
        ws.column_dimensions[col].width = w
    cnt, rev = Counter(x["verdict"] for x in out), Counter()
    for x in out:
        rev[x["verdict"]] += x["rev_mln"]
    s2 = wb.create_sheet("Сводка")
    s2.append(["Итог для нас", "Предметов", "Выручка, млн ₽/мес"])
    for v, n in cnt.most_common():
        s2.append([v, n, round(rev[v], 1)])
    xlsx = ROOT_DIR / "reports" / f"niche_requirements_{TODAY}.xlsx"
    wb.save(xlsx)
    print(f"предметов: {len(out)}")
    for v, n in cnt.most_common():
        print(f"{v}: {n} ({rev[v]:.0f} млн ₽/мес)")
    print("→", xlsx.relative_to(ROOT_DIR))


if __name__ == "__main__":
    main()
