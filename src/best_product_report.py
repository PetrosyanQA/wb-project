def rank_table():
    out = ["| # | Նիշ | F2 ≤1 լ | F3 маржа | F4 հատ/карт | F5 top-1 | F6 жалоба | Ձախողված ֆիլտրեր |",
           "|---:|---|---|---:|---:|---:|---|---|"]
    for i, n in enumerate(D["niches"], 1):
        f = n["filters"]
        v = "—" if n["vol"] is None else f"{n['vol']}"
        mark = lambda k: "✅" if f[k] else ("❔" if f[k] is None else "❌")
        c = n["complaint"]
        fails = "; ".join(x.split(" ", 1)[0] for x in n["fails"]) or "**չկա — անցնում է**"
        out.append(f"| {i} | {n['name']} | {mark('F2 ≤ 1 л')} {v} | {mark('F3 маржа ≥ 18% и ROI ≥ 60%')} {n['margin']}% | "
                   f"{mark('F4 ≥ 150 шт/карточку')} {n['med_s']} | {mark('F5 top-1 ≤ 25%')} {n['t1']}% | "
                   f"{mark('F6 жалоба ≥ 12%')} {c['top'] or '—'} {c['share']}% ({c['total_neg']}) | {fails} |")
    return "\n".join(out)


