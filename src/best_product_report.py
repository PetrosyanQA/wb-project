def f0(x):
    return f"{x:,.0f}".replace(",", " ")


def ue_table(price, yuan, extra=None):
    rows = [("база", price, BUY), ("цена −15%", price * 0.85, BUY), (f"выкуп −15 п.п. ({BUY - 15:.1f}%)", price, BUY - 15)]
