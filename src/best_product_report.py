    for lbl, p, b in rows:
        r = ue(p, yuan, b)
        ok = r["net_margin_pct"] >= 18 and r["roi_on_goods_pct"] >= 60
        out.append(f"| {lbl} | {f0(p)} | {f0(r['net_profit'])} | {r['net_margin_pct']}% | {r['roi_on_goods_pct']}% | {'✅' if ok else '❌'} |")
