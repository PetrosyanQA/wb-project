def get_cfg(sid: int) -> dict:
    """Словарь ниши с подмешанными общими группами (своя группа ниши имеет приоритет целиком)."""
    cfg = dict(DICTS[sid])
    groups = {g: dict(ms) for g, ms in cfg["groups"].items()}
    for g, ms in COMMON.items():
        if g not in groups:
            groups[g] = dict(ms)
    cfg["groups"] = groups
    cfg.setdefault("blocked", {})
    cfg.setdefault("anchors", {"ЧТО", "КОНСТРУКЦИЯ", "ФУНКЦИЯ"})
    cfg.setdefault("complaint_themes", {})
    return cfg
